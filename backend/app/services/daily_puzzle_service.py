def seed_daily_puzzles() -> Dict[int, List[Dict[str, Any]]]:
    """Create the 180-puzzle bank on import (6 grades x 30 puzzles).

    Returns the puzzle bank dict: {grade: [puzzles]}.
    """
    global _PUZZLE_BANK
    _PUZZLE_BANK = {
        1: _g1_puzzles(),
        2: _g2_puzzles(),
        3: _g3_puzzles(),
        4: _g4_puzzles(),
        5: _g5_puzzles(),
        6: _g6_puzzles(),
    }

    total = sum(len(v) for v in _PUZZLE_BANK.values())
    logger.info("Daily puzzle bank seeded — %d puzzles across %d grades", total, len(_PUZZLE_BANK))
    return _PUZZLE_BANK


def get_puzzle_bank() -> Dict[int, List[Dict[str, Any]]]:
    """Return the puzzle bank, seeding it if not yet initialised."""
    if not _PUZZLE_BANK:
        seed_daily_puzzles()
    return _PUZZLE_BANK


def get_daily_puzzle(grade: int, date_str: str) -> Optional[Dict[str, Any]]:
    """Get the puzzle for a given grade and date.

    Deterministically selects from the pool using a hash of date + grade.
    """
    bank = get_puzzle_bank()
    pool = bank.get(grade)
    if not pool:
        return None

    idx = select_daily_puzzle_index(date_str, grade, len(pool))
    puzzle = pool[idx].copy()
    puzzle["puzzle_id"] = f"dp_{date_str}_{grade}_{idx}"
    puzzle["date"] = date_str
    return puzzle


