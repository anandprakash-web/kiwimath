def get_streak_tier(streak_count: int) -> str:
    """Map streak length to visual tier."""
    for threshold, tier in STREAK_TIERS:
        if streak_count >= threshold:
            return tier
    return "none"


def is_streak_alive(last_puzzle_date: str, today: str) -> bool:
    """Check if streak is still alive (last puzzle was yesterday or today)."""
    if not last_puzzle_date:
        return False
    last = datetime.strptime(last_puzzle_date, "%Y-%m-%d").date()
    now = datetime.strptime(today, "%Y-%m-%d").date()
    diff = (now - last).days
    return diff <= 1


def compute_streak_after_submission(
    current_streak: int,
    longest_streak: int,
    last_puzzle_date: Optional[str],
    submission_date: str,
) -> Tuple[int, int, str]:
    """Update streak counts after a puzzle submission.

    Returns (new_current_streak, new_longest_streak, new_last_puzzle_date).
    """
    if not last_puzzle_date:
        # First ever submission
        return 1, max(longest_streak, 1), submission_date

    last = datetime.strptime(last_puzzle_date, "%Y-%m-%d").date()
    today = datetime.strptime(submission_date, "%Y-%m-%d").date()
    diff = (today - last).days

    if diff == 0:
        # Already submitted today — no change
        return current_streak, longest_streak, last_puzzle_date
    elif diff == 1:
        # Consecutive day — extend streak
        new_streak = current_streak + 1
        return new_streak, max(longest_streak, new_streak), submission_date
    else:
        # Streak broken — reset to 1
        return 1, longest_streak, submission_date


def get_freeze_window_start(today_str: str) -> str:
    """Get the Monday of the current week (freeze resets weekly on Monday)."""
    today = datetime.strptime(today_str, "%Y-%m-%d").date()
    monday = today - timedelta(days=today.weekday())
    return monday.strftime("%Y-%m-%d")


# ---------------------------------------------------------------------------
# Daily puzzle selection (deterministic hash)
# ---------------------------------------------------------------------------

def select_daily_puzzle_index(date_str: str, grade: int, pool_size: int = PUZZLES_PER_GRADE) -> int:
    """Deterministically select a puzzle index for a given date + grade.

    Uses SHA-256 hash to ensure same date+grade always yields same puzzle,
    but different grades get different puzzles.
    """
    seed = f"kiwimath_daily_{date_str}_grade_{grade}"
    h = hashlib.sha256(seed.encode()).hexdigest()
    return int(h[:8], 16) % pool_size


def get_puzzle_time_window(date_str: str) -> Dict[str, str]:
    """Get the drop and close times for a given date.

    drops_at  = 4:00 PM IST = 10:30 UTC
    closes_at = 10:00 PM IST = 16:30 UTC
    """
    d = datetime.strptime(date_str, "%Y-%m-%d")
    drops_utc = d.replace(hour=10, minute=30, second=0, tzinfo=timezone.utc)
    closes_utc = d.replace(hour=16, minute=30, second=0, tzinfo=timezone.utc)
    return {
        "drops_at": drops_utc.isoformat(),
        "closes_at": closes_utc.isoformat(),
    }


def is_within_puzzle_window(date_str: str) -> bool:
    """Check if current UTC time is within the puzzle window for the given date."""
    window = get_puzzle_time_window(date_str)
    now = datetime.now(timezone.utc)
    drops = datetime.fromisoformat(window["drops_at"])
    closes = datetime.fromisoformat(window["closes_at"])
    return drops <= now <= closes


