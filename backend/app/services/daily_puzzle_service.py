# ---------------------------------------------------------------------------
# IPS Scoring
# ---------------------------------------------------------------------------

def compute_speed_score(time_taken_seconds: float) -> float:
    """Compute speed component (0.0 to 1.0). Under 30s = max, linear to 0 at 300s."""
    if time_taken_seconds <= SPEED_MAX_SECONDS:
        return 1.0
    if time_taken_seconds >= SPEED_ZERO_SECONDS:
        return 0.0
    return (SPEED_ZERO_SECONDS - time_taken_seconds) / (SPEED_ZERO_SECONDS - SPEED_MAX_SECONDS)


def compute_streak_score(streak_count: int) -> float:
    """Compute streak component (0.0 to 1.0) based on current streak length."""
    if streak_count <= 0:
        return 0.0
    bonus = STREAK_BONUS_TABLE.get(streak_count, STREAK_BONUS_MAX)
    return min(1.0, bonus / STREAK_BONUS_MAX)


def get_streak_bonus_points(streak_count: int) -> int:
    """Get the raw streak bonus points for display."""
    if streak_count <= 0:
        return 0
    return STREAK_BONUS_TABLE.get(streak_count, STREAK_BONUS_MAX)


def compute_ips(
    correct: bool,
    time_taken_seconds: float,
    streak_count: int,
    is_first_attempt: bool = True,
    is_early_bird: bool = False,
) -> Dict[str, Any]:
    """Compute the full IPS (Intelligent Puzzle Score).

    Returns dict with component breakdown and total.
    """
    # Accuracy: 500 if correct, 0 if wrong
    accuracy_pts = int(IPS_MAX * ACCURACY_WEIGHT) if correct else 0

    # Speed: max 300, linear decay
    speed_factor = compute_speed_score(time_taken_seconds) if correct else 0.0
    speed_pts = int(IPS_MAX * SPEED_WEIGHT * speed_factor)

    # Streak: max 150
    streak_factor = compute_streak_score(streak_count) if correct else 0.0
    streak_pts = int(IPS_MAX * STREAK_WEIGHT * streak_factor)

    # Bonus: max 50 (early bird + first attempt)
    bonus_pts = 0
    if correct:
        if is_first_attempt:
            bonus_pts += 25
        if is_early_bird:
            bonus_pts += 25

    total = accuracy_pts + speed_pts + streak_pts + bonus_pts

    return {
        "total": min(IPS_MAX, total),
        "accuracy_pts": accuracy_pts,
        "speed_pts": speed_pts,
        "streak_pts": streak_pts,
        "bonus_pts": bonus_pts,
        "speed_factor": round(speed_factor, 3),
        "streak_factor": round(streak_factor, 3),
    }


